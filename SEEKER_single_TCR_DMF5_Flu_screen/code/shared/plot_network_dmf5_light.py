best_phi, best_cl = 0.0, -1.0
for k in range(16):
    phi = 2 * np.pi * k / 16
    u = np.array([np.cos(phi), np.sin(phi)])
    a0 = np.array(pos[ANCHOR]) + 0.062 * u
    a1 = np.array(pos[ANCHOR]) + 0.095 * u
