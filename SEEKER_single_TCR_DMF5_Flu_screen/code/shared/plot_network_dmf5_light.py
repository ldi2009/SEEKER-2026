"""
DMF5 peptide network - wide light publication figure (PDF / SVG / EPS / PNG)
Data: results/dmf5_network/nodes.csv + links.csv (generated by pipeline_all_networks.py)
Layout: d<=3 spring (seed=42) -> rotate 90 deg clockwise (tall cluster lies down to
        fit the wide canvas, near-isotropic rendering)
        -> hull-ray placement of the outer ring in render space (pure isolates +
        far groups) with even visual gaps; d=4 bridge satellites keep their spring
        positions
Output: results/dmf5_network/peptide_network_DMF5_{all_edges,dist_le3,dist_le2}_light.* (shared layout)
        results/dmf5_network/peptide_network_DMF5_dist_eq1_light.* (nearest-neighbour islands, rendered separately)
Edge style: d=1-2 solid dark (near-black/dark gray), d=3-4 pale (light/very light gray)
        - close neighbours stand out, distant relations fade into the background
Granularity (shared layout, progressively denser for comparison): d<=2 main component
        117 (family structure); d<=3 main component 271 (recommended main figure);
        d<=4 full 5,531 edges
dist_eq1 (nearest-neighbour islands): of 295 nodes only 61 have a d=1 neighbour
        (25 components: 6/5/3/3/3/3 + 19 pairs); the other 234 keep their cluster
        colors but are smaller, paler and unlabelled - every point's color still
        maps to its cluster while the island hierarchy is preserved; d=1 edges are
        drawn above the nodes
        (the spring layout pulls d=1 pairs to < node diameter; drawn below, 37% of
        the edges would be completely hidden)
Anchor: star TLLGFGSCV = top enriched peptide (degree=77), filled with the DMF5 TCR
        color (#E53935, matching the Combined figure)
Data scale: raw CSV 10,000 rows (7,962 standard 9-mers); network takes the top 300
        deduplicated = 295 nodes
Full distribution: of 43,365 pairs d=1:38 (0.09%) d=2:293 (0.68%) d=3:1410 (3.3%)
        d=4:3790 (8.7%) d>=5:37834 (87%) - versus the Flu library where d<=3 covers
        45.3%, DMF5 has only 4.0%: extremely sparse
"""
