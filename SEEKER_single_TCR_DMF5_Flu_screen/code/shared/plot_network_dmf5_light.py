# ---------------- Layout: d<=3 spring -> rotate 90 deg ----------------
HK = nx.Graph(); HK.add_nodes_from(G.nodes)
for u, v, d in G.edges(data="hamming"):
    if d <= K:
        HK.add_edge(u, v)
main_comp = max(nx.connected_components(HK), key=len)

L = nx.Graph(); L.add_nodes_from(G.nodes)
for u, v, d in G.edges(data="hamming"):
    if d <= K:
        L.add_edge(u, v, spring_w=1.0 / d ** 3)
    elif u not in main_comp or v not in main_comp:
        L.add_edge(u, v, spring_w=1.0 / (K + 1) ** 3)

pos = nx.spring_layout(L, k=0.42, iterations=2000, seed=SEED, weight="spring_w")
# Rotate 90 deg clockwise: the tall main cluster lies down and the wide canvas
# renders near-isotropically (avoiding a 2.5x x-stretch)
pos = {n: (pos[n][1], -pos[n][0]) for n in pos}

main_xy = np.array([pos[n] for n in main_comp])
_c = main_xy.mean(axis=0)
_r_max = np.linalg.norm(main_xy - _c, axis=1).max()

# ---------------- Ring groups: pure isolates (deg=0) + far groups ----------------
nonmain = [n for n in G.nodes if n not in main_comp]
S = G.subgraph(nonmain)
ring_groups, kept = [], []
for comp in nx.connected_components(S):
    cen = np.mean([pos[n] for n in comp], axis=0)
    far = np.linalg.norm(cen - _c) > FAR_FACTOR * _r_max
    if len(comp) == 1 and G.degree(next(iter(comp))) == 0:
        ring_groups.append(sorted(comp))          # pure isolate
    elif len(comp) > 1 and far:
        ring_groups.append(sorted(comp))          # far group flung away by the spring layout
    else:
        kept.append(sorted(comp))                 # d=4 bridge satellites keep spring positions
print(f"ring groups ({len(ring_groups)}): {[g[0] + ('+' + str(len(g)-1) if len(g) > 1 else '') for g in ring_groups]}")

# ---------------- Ring placement via hull rays in render space ----------------
# 1) render scale ptx/pty: points per data unit once the content (ring + label
#    margins) fills the canvas
blob = list(main_comp) + [n for g in kept for n in g]
blob_xy = np.array([pos[n] for n in blob])
cx, cy = blob_xy.mean(axis=0)
W_pt = FIGSIZE_IN[0] * 72 * 0.94
H_pt = FIGSIZE_IN[1] * 72 * 0.94
span0x, span0y = np.ptp(blob_xy[:, 0]), np.ptp(blob_xy[:, 1])
ptx, pty = W_pt / span0x, H_pt / span0y
for _ in range(4):
    spanx = span0x + 2 * (GAP_PT + 18) / ptx      # 18pt: outward margin for ring-node labels
    spany = span0y + 2 * (GAP_PT + 18) / pty
    ptx, pty = W_pt / spanx, H_pt / spany
print(f"render scale: ptx={ptx:.0f} pty={pty:.0f} (ratio {ptx/pty:.2f}, closer to 1 is more isotropic)")

# 2) render-space convex hull of main cluster + satellites
Rb = np.array([((pos[n][0] - cx) * ptx, (pos[n][1] - cy) * pty) for n in blob])
hull_pts = Rb[ConvexHull(Rb).vertices]
hull_r_max = np.linalg.norm(hull_pts, axis=1).max()

def hull_ray_radius(phi):
    """Radius (render pt) where the ray from the centroid at angle phi crosses the hull"""
    d = np.array([np.cos(phi), np.sin(phi)])
    P, Q = hull_pts, np.roll(hull_pts, -1, axis=0)
    ts = []
    for p, q in zip(P, Q):
        e = q - p
        A = np.array([[d[0], -e[0]], [d[1], -e[1]]])
        if abs(np.linalg.det(A)) < 1e-9:
            continue
        t, s = np.linalg.solve(A, p)
        if t > 1e-9 and -1e-9 <= s <= 1 + 1e-9:
            ts.append(t)
    return min(ts) if ts else 0.0

def ring_slot_xy(phi):
    t = max(hull_ray_radius(phi) + GAP_PT, 0.45 * hull_r_max + GAP_PT)
    return (cx + t * np.cos(phi) / ptx, cy + t * np.sin(phi) / pty)

# 3) Adaptive slots: 6 sectors of 60 deg each, picking the direction where ring
#    points sit closest to the main component's mass (avoiding concave bays).
#    Closeness is scored on main-component nodes only (d=4 satellites have no edge
#    in the le3 version and would float, misrepresenting the outline); the placement
#    radius still uses the full blob hull so nothing overlaps
Rb_main = np.array([((pos[n][0] - cx) * ptx, (pos[n][1] - cy) * pty) for n in main_comp])

def clearance_at(phi):
    t = hull_ray_radius(phi) + GAP_PT + 18.0
    R = np.array([t * np.cos(phi), t * np.sin(phi)])
    return float(np.min(np.linalg.norm(Rb_main - R, axis=1))), t

N = len(ring_groups)
slots, used_phis = [], []
for sec in range(N):
    lo, hi = 2 * np.pi * sec / N, 2 * np.pi * (sec + 1) / N
    best_phi, best_cl = None, 1e9
    for phi_d in range(int(np.degrees(lo)), int(np.degrees(hi))):
        phi = np.deg2rad(phi_d)
        cl, t = clearance_at(phi)
        if t < 0.5 * hull_r_max:
            continue
        # keep >= 20 deg separation from already-placed slots (wrapping across 0)
        if any(abs((phi - p + np.pi) % (2 * np.pi) - np.pi) < np.deg2rad(20) for p in used_phis):
            continue
        if cl < best_cl:
            best_cl, best_phi = cl, phi
    if best_phi is None:                        # whole sector excluded by spacing -> relax it
        for phi_d in range(int(np.degrees(lo)), int(np.degrees(hi))):
            phi = np.deg2rad(phi_d)
            cl, t = clearance_at(phi)
            if t >= 0.5 * hull_r_max and cl < best_cl:
                best_cl, best_phi = cl, phi
    slots.append(best_phi)
    used_phis.append(best_phi)

def rangle(g):
    cen = np.mean([pos[n] for n in g], axis=0)
    return np.arctan2((cen[1] - cy) * pty, (cen[0] - cx) * ptx) % (2 * np.pi)

ring_groups.sort(key=rangle)
slots.sort()
for g, phi in zip(ring_groups, slots):
    if len(g) == 1:
        r_g = 3.0
    else:
        cen = np.mean([pos[n] for n in g], axis=0)
        r_g = max(np.hypot((pos[n][0] - cen[0]) * ptx, (pos[n][1] - cen[1]) * pty)
                  for n in g) + 3.0
    t = hull_ray_radius(phi) + GAP_PT + r_g
    tx, ty = cx + t * np.cos(phi) / ptx, cy + t * np.sin(phi) / pty
    print(f"  slot {np.degrees(phi):5.1f}deg (hull_r={hull_ray_radius(phi):5.0f}pt cl={clearance_at(phi)[0]:5.0f}pt) <- {g[0]}{'+' + str(len(g)-1) if len(g) > 1 else ''}")
    if len(g) == 1:
        pos[g[0]] = (tx, ty)
    else:
        # move the whole small group to its slot, preserving internal shape
        cen = np.mean([pos[n] for n in g], axis=0)
        offs = {n: (pos[n][0] - cen[0], pos[n][1] - cen[1]) for n in g}
        m = max(np.linalg.norm(o) for o in offs.values())
        scale = min(1.0, 0.05 / m) if m > 0 else 1.0
        for n in g:
            pos[n] = (tx + offs[n][0] * scale, ty + offs[n][1] * scale)

